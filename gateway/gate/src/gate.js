// Shared access gate for Litehouse DeepTech demo sites.
// Codes live in the KV namespace bound as CODES under the key "code:<site>".
// Codes are exactly six digits. A site with no code set stays locked: nobody can
// enter until the owner sets its code in the admin panel.
// The session cookie is an HMAC of the site and its current code, so changing a
// code in the admin panel signs everyone out of that site at once.

const MAX_AGE = 60 * 60 * 24 * 7; // seven days

export async function currentCode(env, site) {
  try {
    const v = await env.CODES.get("code:" + site);
    if (v && /^[0-9]{6}$/.test(v)) return v;
  } catch (_) {}
  return null;
}

async function hmac(secret, msg) {
  const key = await crypto.subtle.importKey("raw", new TextEncoder().encode(secret),
    { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const sig = await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(msg));
  return [...new Uint8Array(sig)].map(b => b.toString(16).padStart(2, "0")).join("");
}

// The cookie-signing secret is generated by the gate on first use and kept in KV,
// so it never has to be typed into a dashboard.
let secretCache = null;
async function gateSecret(env) {
  if (secretCache) return secretCache;
  let v = await env.CODES.get("gate:secret");
  if (!v) {
    v = [...crypto.getRandomValues(new Uint8Array(32))].map(b => b.toString(16).padStart(2, "0")).join("");
    const again = await env.CODES.get("gate:secret");
    if (again) v = again; else await env.CODES.put("gate:secret", v);
  }
  return (secretCache = v);
}

function cookieName(site) { return "lh_" + site; }

function readCookie(request, name) {
  const raw = request.headers.get("cookie") || "";
  for (const part of raw.split(/;\s*/)) {
    const i = part.indexOf("=");
    if (i > 0 && part.slice(0, i) === name) return part.slice(i + 1);
  }
  return null;
}

function timingSafeEqual(a, b) {
  if (typeof a !== "string" || typeof b !== "string" || a.length !== b.length) return false;
  let r = 0;
  for (let i = 0; i < a.length; i++) r |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return r === 0;
}

