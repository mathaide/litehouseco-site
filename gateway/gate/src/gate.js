// Returns a Response if the gate must answer (login page, login result, logout),
// or null if the visitor is signed in and the request may proceed.
export async function gate(request, env, site, title) {
  const url = new URL(request.url);
  const code = await currentCode(env, site);
  if (!code) {
    if (url.pathname === "/__access") await new Promise(r => setTimeout(r, 600));
    return loginPage(title, false, 503, true);
  }
  const good = await hmac(await gateSecret(env), site + ":" + code);
  const name = cookieName(site);

  if (url.pathname === "/__access" && request.method === "POST") {
    let given = "";
    try { const f = await request.formData(); given = String(f.get("code") || "").trim(); } catch (_) {}
    if (timingSafeEqual(given, code)) {
      return new Response(null, { status: 303, headers: {
        location: "/", "cache-control": "no-store",
        "set-cookie": `${name}=${good}; Path=/; Max-Age=${MAX_AGE}; HttpOnly; Secure; SameSite=Lax` } });
    }
    await new Promise(r => setTimeout(r, 600)); // slow down guessing
    return loginPage(title, true);
  }
  if (url.pathname === "/__logout") {
    return new Response(null, { status: 303, headers: { location: "/",
      "set-cookie": `${name}=; Path=/; Max-Age=0; HttpOnly; Secure; SameSite=Lax` } });
  }
  const have = readCookie(request, name);
  if (have && timingSafeEqual(have, good)) return null;
  if (request.method !== "GET" && request.method !== "HEAD") {
    return new Response(JSON.stringify({ error: "Access code required." }), { status: 401,
      headers: { "content-type": "application/json", "cache-control": "no-store" } });
  }
  return loginPage(title, false);
}
